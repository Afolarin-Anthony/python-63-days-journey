# Module of the day is Statistics
# The module is extremely useful for:
# - Data Analysis
# - Reports
# - Machine Learning
# - Scientific computing

import statistics

scores = [60, 75, 80, 90, 95]

# Finding the mean(average)
print(statistics.mean(scores))

# Finding the median (the middle value)
print(statistics.median(scores))

# Finding the mode (most frequently occurring value)
data = [1, 2, 2, 3, 3, 3]
print(statistics.mode(data))

# Standard Deviation (measuring how spread out data is)

data = [10, 12, 14, 16, 18]
print(statistics.stdev(data))

